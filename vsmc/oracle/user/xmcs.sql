-- Create profile
CREATE PROFILE XMCS_PROFILE LIMIT
SESSIONS_PER_USER 1100
CONNECT_TIME UNLIMITED
IDLE_TIME UNLIMITED
CPU_PER_SESSION UNLIMITED
CPU_PER_CALL UNLIMITED
LOGICAL_READS_PER_SESSION UNLIMITED
LOGICAL_READS_PER_CALL UNLIMITED
PRIVATE_SGA UNLIMITED
COMPOSITE_LIMIT UNLIMITED
PASSWORD_LIFE_TIME UNLIMITED
FAILED_LOGIN_ATTEMPTS UNLIMITED
/

-- Create user
CREATE USER @@CORE_USER@@ IDENTIFIED BY @@CORE_PW@@
DEFAULT TABLESPACE CONTROL_DATA
TEMPORARY TABLESPACE TEMP
PROFILE XMCS_PROFILE
/
-- Grants.
GRANT connect,resource TO @@CORE_USER@@ WITH ADMIN OPTION
/
GRANT DBA TO @@CORE_USER@@ WITH ADMIN OPTION
/
GRANT SELECT ANY DICTIONARY TO @@CORE_USER@@ WITH ADMIN OPTION
/
GRANT UNLIMITED TABLESPACE TO @@CORE_USER@@ WITH ADMIN OPTION
/
GRANT CREATE ANY TABLE TO @@CORE_USER@@ WITH ADMIN OPTION
/
GRANT CREATE ANY INDEX TO @@CORE_USER@@ WITH ADMIN OPTION
/
GRANT ALTER ANY TABLE TO @@CORE_USER@@ WITH ADMIN OPTION
/
GRANT ALTER ANY INDEX TO @@CORE_USER@@ WITH ADMIN OPTION
/
GRANT DROP ANY TABLE TO @@CORE_USER@@ WITH ADMIN OPTION
/
GRANT DROP ANY INDEX TO @@CORE_USER@@ WITH ADMIN OPTION
/
GRANT CREATE ANY PROCEDURE TO @@CORE_USER@@ WITH ADMIN OPTION
/
GRANT CREATE ANY SYNONYM TO @@CORE_USER@@ WITH ADMIN OPTION
/
GRANT CREATE ANY VIEW TO @@CORE_USER@@ WITH ADMIN OPTION
/
GRANT CREATE EVALUATION CONTEXT TO @@CORE_USER@@ WITH ADMIN OPTION
/
GRANT CREATE RULE TO @@CORE_USER@@ WITH ADMIN OPTION
/

-- print current dba_role_privs
SELECT * FROM DBA_ROLE_PRIVS WHERE GRANTEE= '@@CORE_USER@@'
/
-- print current dba_sys_privs
SELECT * FROM DBA_SYS_PRIVS  WHERE GRANTEE = '@@CORE_USER@@'
/

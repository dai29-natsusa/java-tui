-- Create profile
CREATE PROFILE EMU_PROFILE LIMIT
SESSIONS_PER_USER 1100
CONNECT_TIME UNLIMITED
IDLE_TIME UNLIMITED
CPU_PER_SESSION UNLIMITED
CPU_PER_CALL UNLIMITED
LOGICAL_READS_PER_SESSION UNLIMITED
LOGICAL_READS_PER_CALL UNLIMITED
PRIVATE_SGA UNLIMITED
COMPOSITE_LIMIT UNLIMITED
PASSWORD_LIFE_TIME UNLIMITED
FAILED_LOGIN_ATTEMPTS UNLIMITED
/

-- Create user
CREATE USER @@EMU_USER@@ IDENTIFIED BY @@EMU_PW@@
DEFAULT TABLESPACE CONTROL_DATA
TEMPORARY TABLESPACE TEMP
PROFILE EMU_PROFILE
/
-- Grants.
GRANT connect,resource TO @@EMU_USER@@ WITH ADMIN OPTION
/
GRANT DBA TO @@EMU_USER@@ WITH ADMIN OPTION
/
GRANT SELECT ANY DICTIONARY TO @@EMU_USER@@ WITH ADMIN OPTION
/
GRANT UNLIMITED TABLESPACE TO @@EMU_USER@@ WITH ADMIN OPTION
/
GRANT CREATE ANY TABLE TO @@EMU_USER@@ WITH ADMIN OPTION
/
GRANT CREATE ANY INDEX TO @@EMU_USER@@ WITH ADMIN OPTION
/
GRANT ALTER ANY TABLE TO @@EMU_USER@@ WITH ADMIN OPTION
/
GRANT ALTER ANY INDEX TO @@EMU_USER@@ WITH ADMIN OPTION
/
GRANT DROP ANY TABLE TO @@EMU_USER@@ WITH ADMIN OPTION
/
GRANT DROP ANY INDEX TO @@EMU_USER@@ WITH ADMIN OPTION
/
GRANT CREATE ANY PROCEDURE TO @@EMU_USER@@ WITH ADMIN OPTION
/
GRANT CREATE ANY SYNONYM TO @@EMU_USER@@ WITH ADMIN OPTION
/
GRANT CREATE ANY VIEW TO @@EMU_USER@@ WITH ADMIN OPTION
/
GRANT CREATE EVALUATION CONTEXT TO @@EMU_USER@@ WITH ADMIN OPTION
/
GRANT CREATE RULE TO @@EMU_USER@@ WITH ADMIN OPTION
/

-- print current dba_role_privs
SELECT * FROM DBA_ROLE_PRIVS WHERE GRANTEE= '@@EMU_USER@@'
/
-- print current dba_sys_prive
SELECT * FROM DBA_SYS_PRIVS  WHERE GRANTEE = '@@EMU_USER@@'
/

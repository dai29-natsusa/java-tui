-- Create profile
BEGIN
    EXECUTE IMMEDIATE 'CREATE PROFILE XMCS_PROFILE LIMIT
    SESSIONS_PER_USER 1100
    CONNECT_TIME UNLIMITED
    IDLE_TIME UNLIMITED
    CPU_PER_SESSION UNLIMITED
    CPU_PER_CALL UNLIMITED
    LOGICAL_READS_PER_SESSION UNLIMITED
    LOGICAL_READS_PER_CALL UNLIMITED
    PRIVATE_SGA UNLIMITED
    COMPOSITE_LIMIT UNLIMITED
    PASSWORD_LIFE_TIME UNLIMITED
    FAILED_LOGIN_ATTEMPTS UNLIMITED';
EXCEPTION
    WHEN OTHERS THEN
        IF SQL_CODE = -1184 THEN
            DBMS_OUTPUT.PUT_LINE('Profile already existing');
        ELSE
            RAISE;
        END IF;
END;
/

-- Create user
BEGIN
    EXECUTE IMMEDIATE 'CREATE USER @@USR@@ IDENTIFIED BY @@PSW@@
    DEFAULT TABLESPACE CONTROL_DATA
    TEMPORARY TABLESPACE TEMP
    PROFILE XMCS_PROFILE';
EXCEPTION
   WHEN OTHERS THEN
      IF SQLCODE = -1920 THEN
         DBMS_OUTPUT.PUT_LINE('User already exists.');
      ELSE
         RAISE;
      END IF;
END;
